#include <stdio.h>

int main(void)
{
    int n, n1 = 0, cnt = 0;

    scanf("%d", &n);
    n1 = n;

    /* 第一步：统计 n 有几位（每除一次 10 就去掉一位） */
    while (n1 > 0) {
        n1 /= 10;
        cnt++;
    }

    int cnt1 = cnt;
    int cnt2 = cnt;
    char a[cnt + 1];   /* 存放拆出来的每一位，a[0] 是最高位 */

    /* 第二步：造除数 b = 10^(cnt-1)
       例：7 位数时 b = 1000000，n / b 正好取出最高位那个数字 */
    int b = 1;
    for (; cnt1 > 1; cnt1--) {
        b *= 10;
    }

    /* 第三步：逐位拆进数组
       n / b   → 当前最高位数字，+'0' 转成字符存入 a[i]
       n %= b  → 从 n 里砍掉刚取走的最高位
       b /= 10 → 除数缩小一位，下一轮取次高位 */
    for (int i = 0; i < cnt; i++) {
        a[i] = n / b + '0';
        n %= b;
        b /= 10;
    }

    /* 第四步：输出 —— 从最高位往低位遍历；
       某位右边还剩的位数（cnt2-1-i）是 3 的倍数时，在它后面插逗号，
       等价于从最低位起每 3 位一组（千分位本来就从个位往前数） */
    for (int i = 0; i < cnt2; i++) {
        if ((cnt2 - 1 - i) % 3 == 0 && cnt2 - 1 != i) {
            printf("%c,", a[i]);   /* 该插逗号：打数字再打逗号 */
        } else {
            printf("%c", a[i]);    /* 普通位：只打数字 */
        }
    }

    return 0;
}
